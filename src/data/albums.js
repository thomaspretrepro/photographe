// Helper function to get album by ID
export const getAlbumById = (id) => {
  return albumsData.find(album => album.id === id);
};

// Helper function to get albums for gallery (without photos data for performance)
export const getGalleryAlbums = () => {
  const albums = albumsData.map(({ photos, ...album }) => ({
    ...album,
    photoCount: photos.length
  }));

  // Détection de conflits de displayOrder (avertissement dev uniquement)
  if (process.env.NODE_ENV === 'development') {
    const orderMap = {};
    albums.forEach(a => {
      if (!a.eventDate && a.displayOrder !== undefined) {
        if (!orderMap[a.displayOrder]) orderMap[a.displayOrder] = [];
        orderMap[a.displayOrder].push(a.id);
      }
    });
    Object.entries(orderMap).forEach(([order, ids]) => {
      if (ids.length > 1) {
        console.warn(
          `⚠️  Conflit de displayOrder (${order}) entre les albums : ${ids.join(', ')}. ` +
          `Modifie src/data/albums.js pour leur attribuer des valeurs uniques.`
        );
      }
    });
  }

  const toTime = (value) => {
    const t = new Date(value || 0).getTime();
    return Number.isNaN(t) ? 0 : t;
  };

  return albums.sort((a, b) => {
    const hasDateA = Boolean(a.eventDate);
    const hasDateB = Boolean(b.eventDate);

    // eventDate prioritaire : albums datés d'abord, du plus récent au plus ancien
    if (hasDateA && hasDateB) {
      const dateDiff = toTime(b.eventDate) - toTime(a.eventDate);
      if (dateDiff !== 0) return dateDiff;
    } else if (hasDateA !== hasDateB) {
      return hasDateA ? -1 : 1;
    }

    const orderDiff = (a.displayOrder ?? 999) - (b.displayOrder ?? 999);
    if (orderDiff !== 0) return orderDiff;
    // Tie-breaker : createdAt, le plus récent en premier
    return toTime(b.createdAt) - toTime(a.createdAt);
  });
};

// Helper function to get all unique categories
export const getAllCategories = () => {
  const categories = [...new Set(albumsData.map(album => album.category))];
  return categories.sort();
};

// Helper function to get albums by category
export const getAlbumsByCategory = (category) => {
  return albumsData.filter(album => album.category === category);
};

// Helper function to get recent albums
export const getRecentAlbums = (limit = 3) => {
  return albumsData
    .sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt))
    .slice(0, limit);
};

// Helper function to search albums
export const searchAlbums = (query) => {
  const searchTerm = query.toLowerCase();
  return albumsData.filter(album => 
    album.title.toLowerCase().includes(searchTerm) ||
    album.description.toLowerCase().includes(searchTerm)
  );
};